#!/usr/bin/env python3
import argparse, json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).parents[1]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--config", type=Path, default=ROOT / "scripts/sae/selection/config.json")
    p.add_argument("--dir", type=Path, default=ROOT / "results/sae_feature_selection")
    p.add_argument("--scores", type=Path, default=None, help="default: <dir>/steering_scores.csv")
    p.add_argument("--depth-file", type=Path, default=None, help="ranks searched per layer (for the record)")
    p.add_argument("--features-file", type=Path, default=None, help="default: <dir>/sweep_features.txt")
    args = p.parse_args()
    args.features_file = args.features_file or args.dir / "sweep_features.txt"
    cfg = json.loads(args.config.read_text())
    rule = cfg["pass_rule"]
    depth = json.loads(args.depth_file.read_text()) if args.depth_file else {}
    cand = pd.read_csv(args.dir / "candidates.csv")
    lab = pd.read_csv(args.dir / "concept_labels.csv")[["feature_id", "semantic", "category", "reason"]]
    sc = pd.read_csv(args.scores or args.dir / "steering_scores.csv")
    sc = sc.rename(columns={"feature": "feature_id"})
    sc = sc[["feature_id", "judged", "hit", "hit_all", "steered", *[c for c in sc if c.startswith("steer_x")], "baseline"]]
    df = cand.merge(lab, on="feature_id", how="left").merge(sc, on="feature_id", how="left")

    df["passes_steering"] = (df.judged >= rule["min_judged"]) & (df["hit" if rule.get("hit_rule", "any") == "any" else "hit_all"] >= rule["min_hit"])
    df["eligible"] = (df.semantic == True) & df.passes_steering
    df["selected"] = False
    df["status"] = ""
    df.loc[df.semantic != True, "status"] = "not semantic: " + df.category.astype(str)
    df.loc[(df.semantic == True) & df.judged.isna(), "status"] = "semantic, not judged"
    df.loc[(df.semantic == True) & df.judged.notna() & ~df.passes_steering, "status"] = "semantic, failed steering"
    lines = []
    for L in cfg["layers"]:
        k = int(cfg["n_select"].get(str(L), cfg["n_select"]["default"]))
        pick = df[(df.layer == L) & df.eligible].sort_values("rank").head(k)
        df.loc[pick.index, "selected"] = True
        df.loc[(df.layer == L) & df.eligible & ~df.selected, "status"] = "eligible, lower rank"
        df.loc[pick.index, "status"] = [f"selected F{i}" for i in range(1, len(pick) + 1)]
        ids = pick.feature_id.tolist()
        searched = depth.get(str(L), int((df.layer == L).sum()))
        note = "" if len(ids) == k else f"   # only {len(ids)} of {k} eligible (searched ranks 1-{searched})"
        lines.append(f"{L:<3} " + "  ".join(f"{x:<10}" for x in ids) + note)
        print(f"layer {L:2d}: {len(ids)}/{k} selected  {ids}  (ranks 1-{searched})"
              f"   (semantic {int((df[df.layer == L].semantic == True).sum())}, "
              f"eligible {int(df[(df.layer == L) & df.eligible].shape[0])})")
    other = df[df.category == "other"]
    if len(other):
        print(f"{len(other)} candidates fell outside the rubric (category 'other', not selected):")
        print(other[["feature_id", "rank", "explanation", "reason"]].to_string(index=False))
    df.to_csv(args.dir / "selection_record.csv", index=False)
    header = ("# Generated by data_prep/sae_select_features.py from results/sae_feature_selection/ "
              "(config: scripts/sae/selection/config.json).\n"
              "# One line per layer: LAYER F1 F2 F3 ... (ranked). Do not edit by hand; rerun the selection.\n")
    args.features_file.write_text(header + "\n".join(lines) + "\n")
    print(f"wrote {args.dir / 'selection_record.csv'} and {args.features_file}")


if __name__ == "__main__":
    main()
